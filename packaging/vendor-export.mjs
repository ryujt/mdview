// Optional maintainer task; release/Go builds use the checked-in browser assets.
// Run with a directory containing the pinned npm packages (see vendor/README.md).
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(process.argv[2] ? join(resolve(process.argv[2]), 'package.json') : import.meta.url);
const { build } = require('esbuild');
const vendor = fileURLToPath(new URL('../internal/mdview/static/vendor/', import.meta.url));
const pins = { marked: '12.0.2', jszip: '3.10.1' };
const sections = [];
const visited = new Set();
async function notices(name, resolver) {
  const packagePath = resolver.resolve(`${name}/package.json`);
  if (visited.has(packagePath)) return;
  visited.add(packagePath);
  const pkg = JSON.parse(await readFile(packagePath, 'utf8'));
  const licenses = [];
  for (const filename of ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'LICENSE.markdown', 'COPYING']) {
    try { licenses.push(await readFile(join(dirname(packagePath), filename), 'utf8')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  if (!licenses.length) {
    const readme = await readFile(join(dirname(packagePath), 'README.md'), 'utf8');
    const license = readme.match(/^#+ License\b[\s\S]*/im);
    if (license) licenses.push(license[0]);
  }
  if (!licenses.length) throw new Error(`Missing license for ${pkg.name}`);
  sections.push(`${pkg.name} ${pkg.version}\n\n${licenses.join('\n\n')}`);
  const childResolver = createRequire(packagePath);
  for (const dependency of Object.keys(pkg.dependencies || {}).sort()) await notices(dependency, childResolver);
}
await mkdir(vendor, { recursive: true });
for (const [name, version] of Object.entries(pins)) {
  const pkgPath = require.resolve(`${name}/package.json`);
  const pkg = JSON.parse(await readFile(pkgPath, 'utf8'));
  if (pkg.version !== version) throw new Error(`Expected ${name}@${version}, found ${pkg.version}`);
  await build({
    stdin: {
      contents: name === 'marked' ? "export { Marked } from './lib/marked.esm.js';" : "export { default } from './dist/jszip.min.js';",
      resolveDir: dirname(pkgPath),
    },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2020', minify: true,
    legalComments: 'eof', outfile: join(vendor, `${name}.js`),
    banner: { js: `// Generated by packaging/vendor-export.mjs from ${name}@${version}. See LICENSES.txt.` },
  });
  await notices(name, require);
}
await writeFile(join(vendor, 'LICENSES.txt'), 'Embedded ZIP export dependencies and their resolved dependencies\n\n' + sections.join('\n\n' + '='.repeat(72) + '\n\n'));
